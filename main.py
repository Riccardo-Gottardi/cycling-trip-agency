from crew.route_planner_agent import route_planner
from crew.route_calculator_agent import route_calculator



def run_route_planner() -> Itinerary | None:
    history: list[ModelMessage] = []
    user_input = ""

    while True:
        result = route_planner.run_sync(user_input, message_history=history)

        if isinstance(result.output, Itinerary):
            return result.output

        # Add to the history the newer messages
        # The ones generated by the last run of the Agent
        history.extend(result.new_messages())

        # Present the Agent response to the user
        print("Agent: ", result.output, sep="\n")

        # Get the input from the user
        # Actually the User response to the Agent response
        user_input = input("User:\n")
        if user_input.lower().strip() in ("exit", "quit"):
            print("The user forced loop termination")
            return None


def run_route_calculator(deps: MyDeps) -> GPXData | None:
    history: list[ModelMessage] = []
    user_input = ""

    while True:
        result = route_calculator.run_sync(user_input, message_history=history, deps=deps)

        if isinstance(result.output, MessageToCustomer):
            # Add to the history the newer messages
            # The ones generated by the last run of the Agent
            history.extend(result.new_messages())

            # Present the Agent response to the user
            print("Agent: ", result.output.message, sep="\n")

            # Get the input from the user
            # Actually the User response to the Agent response
            user_input = input("User:\n")
            if user_input.lower().strip() in ("exit", "quit"):
                print("The user forced loop termination")
                return None

        elif isinstance(result.output, GPXData):
            return result.output


        
